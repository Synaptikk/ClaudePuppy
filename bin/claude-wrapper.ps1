# claude-wrapper.ps1 (VDI variant)
# Reads puppy_token live from Code Puppy config on every launch.
# Auto-starts the sanitizer proxy in the background if it is not already running.
# No hardcoded secrets. When Code Puppy refreshes the token, this picks it up
# automatically.
#
# VDI-specific notes:
#   - $env:USERPROFILE points at FSLogix-mangled C:\Users\<user>; we ignore it
#     and key off $env:USERNAME + the H:\ home drive instead.
#   - The real claude binary is the single self-contained claude.exe shipped
#     in @anthropic-ai/claude-code-win32-x64, dropped at
#     H:\<user>\.local\bin\claude-real.exe by install-vdi.ps1. No Node needed.
#   - Sanitizer is started via sanitizer-launcher.cmd so the launcher's
#     UV_INDEX_URL / HTTP_PROXY env vars are inherited (Walmart pypi mirror,
#     sysproxy). Setting them in PowerShell would not propagate cleanly to
#     a Start-Process'd uv child.

$username   = $env:USERNAME
$puppyHome  = "H:\$username\code-puppy-home"
$userBin    = "H:\$username\.local\bin"

$REAL_CLAUDE        = "$userBin\claude-real.exe"
$PUPPY_CFG          = "$puppyHome\config\code_puppy\puppy.cfg"
$SANITIZER_LAUNCHER = "$userBin\sanitizer-launcher.cmd"
$UPSTREAM_URL       = 'https://puppy-backend.walmart.com/anthropic'
$PROXY_URL          = 'http://127.0.0.1:8787'
$WARN_DAYS          = 14

# -------------------------------------------------------------------------
# 0. Sanity checks - fail fast with a useful message
# -------------------------------------------------------------------------
if (-not (Test-Path $REAL_CLAUDE)) {
    Write-Error "claude-real.exe not found at $REAL_CLAUDE. Re-run install-vdi.ps1 (C:\cp_venvs may have been wiped, or the binary was never installed)."
    exit 1
}
if (-not (Test-Path $SANITIZER_LAUNCHER)) {
    Write-Error "sanitizer-launcher.cmd not found at $SANITIZER_LAUNCHER. Re-run install-vdi.ps1."
    exit 1
}

# -------------------------------------------------------------------------
# 1. Read puppy_token live from puppy.cfg
# -------------------------------------------------------------------------
if (-not (Test-Path $PUPPY_CFG)) {
    Write-Error "puppy.cfg not found at $PUPPY_CFG - is Code Puppy installed and authenticated?"
    exit 1
}

$cfg   = Get-Content $PUPPY_CFG -Raw -ErrorAction Stop
$token = [regex]::Match($cfg, 'puppy_token\s*=\s*(\S+)').Groups[1].Value

if (-not $token) {
    Write-Error "No puppy_token in $PUPPY_CFG - restart Code Puppy to re-authenticate."
    exit 1
}

# -------------------------------------------------------------------------
# 1a. Refresh the local token cache + fast-path helper.
# Claude Code invokes apiKeyHelper on every API request. When the helper
# script itself lives on H:\, cmd.exe spends ~1s per invocation just
# loading the .cmd over SMB (measured: 870-1000ms/call). Mirroring both
# the helper AND the token to a local path on C:\ drops the call to
# ~55ms (18x speedup).
#
# We overwrite both files on every wrapper launch:
#   - puppy_token.txt: picks up token rotations from Code Puppy
#   - get-puppy-token.cmd: guarantees the local helper matches the
#     canonical version even if it was deleted or hand-edited
# -------------------------------------------------------------------------
$tokenCacheDir  = Join-Path $env:LOCALAPPDATA 'ClaudePuppy'
$tokenCacheFile = Join-Path $tokenCacheDir 'puppy_token.txt'
$localHelper    = Join-Path $tokenCacheDir 'get-puppy-token.cmd'
try {
    if (-not (Test-Path $tokenCacheDir)) {
        New-Item -ItemType Directory -Path $tokenCacheDir -Force | Out-Null
    }
    [System.IO.File]::WriteAllText($tokenCacheFile, $token + "`r`n")

    # Inline canonical helper body. Fallback to the H:\ path only if the
    # token cache is somehow missing (first launch, hand-deleted, etc).
    $helperBody = @"
@echo off
:: get-puppy-token.cmd (VDI variant - C:\ fast path)
:: Auto-regenerated by claude-wrapper.ps1 on every launch.
:: DO NOT EDIT - source of truth is claude-wrapper.ps1 in H:\<user>\.local\bin\.
if exist "%LOCALAPPDATA%\ClaudePuppy\puppy_token.txt" (
    type "%LOCALAPPDATA%\ClaudePuppy\puppy_token.txt"
    exit /b 0
)
for /f "tokens=2 delims== " %%a in ('findstr /b "puppy_token" "H:\%USERNAME%\code-puppy-home\config\code_puppy\puppy.cfg"') do @echo %%a
"@
    [System.IO.File]::WriteAllText($localHelper, $helperBody)
} catch {
    Write-Warning "Could not refresh token cache at ${tokenCacheDir}: $_"
}

# -------------------------------------------------------------------------
# 1b. Ensure settings.json points apiKeyHelper at the C:\ helper.
# One-time migration from the old H:\ path. We only rewrite when needed
# so we don't churn the file every launch.
# -------------------------------------------------------------------------
$settingsPath = "$puppyHome\.claude\settings.json"
if (Test-Path $settingsPath) {
    try {
        $settings = Get-Content $settingsPath -Raw | ConvertFrom-Json
        if ($settings.apiKeyHelper -ne $localHelper) {
            $settings.apiKeyHelper = $localHelper
            $settings | ConvertTo-Json -Depth 10 | Set-Content -Path $settingsPath -Encoding UTF8
            Write-Host "[claude-wrapper] Migrated apiKeyHelper -> $localHelper"
        }
    } catch {
        Write-Warning "Could not update apiKeyHelper in ${settingsPath}: $_"
    }
}

# -------------------------------------------------------------------------
# 2. Decode JWT expiry and warn if near
# -------------------------------------------------------------------------
try {
    $payload = $token.Split('.')[1]
    $pad     = 4 - ($payload.Length % 4)
    if ($pad -lt 4) { $payload += '=' * $pad }
    $payload  = $payload.Replace('-', '+').Replace('_', '/')
    $claims   = [System.Text.Encoding]::UTF8.GetString(
                    [System.Convert]::FromBase64String($payload)
                ) | ConvertFrom-Json
    $expiresAt = [DateTimeOffset]::FromUnixTimeSeconds($claims.exp).LocalDateTime
    $daysLeft  = ($expiresAt - (Get-Date)).TotalDays

    if ($daysLeft -lt 0) {
        Write-Error "puppy_token EXPIRED ($expiresAt) - restart Code Puppy to re-authenticate."
        exit 1
    } elseif ($daysLeft -lt $WARN_DAYS) {
        Write-Warning "puppy_token expires in $([math]::Round($daysLeft, 1)) days. Restart Code Puppy soon."
    }
} catch {
    Write-Warning "Could not decode token expiry - proceeding anyway."
}

# -------------------------------------------------------------------------
# 3. Ensure the sanitizer proxy is running on port 8787
# -------------------------------------------------------------------------
function Test-SanitizerAlive {
    # Any HTTP response (including 4xx/5xx) means uvicorn is up.
    # Only a connection-refused / timeout means it is not running yet.
    try {
        Invoke-WebRequest -Uri 'http://127.0.0.1:8787/' -TimeoutSec 2 -ErrorAction Stop | Out-Null
        return $true
    } catch {
        $msg = $_.Exception.Message
        if ($msg -match 'Unable to connect|actively refused|No connection|timed out') {
            return $false
        }
        return $true
    }
}

if (-not (Test-SanitizerAlive)) {
    Write-Host "[claude-wrapper] Starting sanitizer proxy in background..."

    Start-Process -FilePath "cmd.exe" `
        -ArgumentList "/c", "`"$SANITIZER_LAUNCHER`"" `
        -WindowStyle Hidden | Out-Null

    # Wait up to 60 seconds (first run downloads uv deps via the Walmart pypi mirror)
    $ready = $false
    for ($i = 0; $i -lt 120; $i++) {
        Start-Sleep -Milliseconds 500
        if (Test-SanitizerAlive) { $ready = $true; break }
    }

    if (-not $ready) {
        Write-Warning "[claude-wrapper] Sanitizer did not start in time - falling back to direct gateway."
        $PROXY_URL = $UPSTREAM_URL
    } else {
        Write-Host "[claude-wrapper] Sanitizer ready on $PROXY_URL"
    }
} else {
    Write-Host "[claude-wrapper] Sanitizer already running on $PROXY_URL"
}

# -------------------------------------------------------------------------
# 4. Set env vars for this process only (never written to disk).
# Auth is handled exclusively by apiKeyHelper in
# H:\<user>\code-puppy-home\.claude\settings.json which calls
# get-puppy-token.cmd on demand. Setting ANTHROPIC_AUTH_TOKEN here too would
# cause a conflict warning and unpredictable behaviour.
# -------------------------------------------------------------------------
$env:ANTHROPIC_BASE_URL                = $PROXY_URL
$env:DISABLE_TELEMETRY                 = '1'
$env:DISABLE_ERROR_REPORTING           = '1'
$env:DISABLE_AUTOUPDATER               = '1'
$env:DISABLE_NON_ESSENTIAL_MODEL_CALLS = '1'

# -------------------------------------------------------------------------
# 5. Launch Claude Code, passing all args through
# -------------------------------------------------------------------------
& $REAL_CLAUDE @args
exit $LASTEXITCODE
